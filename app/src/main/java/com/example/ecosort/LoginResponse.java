package com.example.ecosort;

public class LoginResponse {

    int id;
    String username;
    String firstName;
    String lastName;
    String email;
    String image;

    public int getId() {
        return id;
    }

    public String getUsername() {
        return username;
    }

    public String getFirstName() {
        return firstName;
    }

    public String getLastName() {
        return lastName;
    }

    public String getEmail() {
        return email;
    }

    public String getImage() {
        return image;
    }
}